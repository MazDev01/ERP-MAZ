/*
 * payruns.sum เก็บบรรทัดของพนักงานทุกคนไว้ข้างใน และนโยบายเดิมให้ทุกคนที่ล็อกอินอ่านได้
 * เท่ากับเปิดเงินเดือนทั้งบริษัทให้ทุกคนดู (เจอตอนไล่ตรวจสิทธิ์ทุกตาราง 17 พ.ย. 2569)
 *
 * สลิปของพนักงานย้ายไปอ่านจาก payslip_lines ซึ่งปล่อยให้เห็นเฉพาะของตัวเอง
 * และเฉพาะรอบที่เผยแพร่สลิปแล้ว ส่วนรอบจ่ายเหลือเฉพาะฝ่ายบุคคลและผู้บริหาร
 */
drop policy if exists payrun_read on public.payruns;
create policy payrun_read on public.payruns for select to authenticated
  using (public.has_role('hr') or public.has_role('ceo'));

