-- ─────────────────────────────────────────────────────────────────
-- รอบที่ 7 — ผู้อนุมัติต้องเห็นชื่อคนที่ตัวเองอนุมัติ
--
-- ของเดิม employees_read ให้เห็นได้แค่ตัวเองกับฝ่ายบุคคล
-- ผลคือคิวอนุมัติของ GM อ่านใบลาได้ (leave_read ให้สิทธิ์ไว้) แต่แปลงรหัส
-- พนักงานเป็นชื่อไม่ได้ ใบจึงหายไปจากคิวทั้งใบ — ผู้อนุมัติไม่เห็นว่ามีอะไรรออยู่
-- (เจอตอนทดสอบสายใบลาบนเบราว์เซอร์จริง 2 พ.ย. 2569)
--
-- กติกาใหม่ เห็นได้เมื่อเป็นอย่างใดอย่างหนึ่ง
--   ตัวเอง
--   ฝ่ายบุคคล (ดูแลข้อมูลพนักงานทั้งบริษัท)
--   ลูกทีมของตัวเอง (boss_id)
--   คนที่ตำแหน่งงานของเขาส่งคำขอมาถึงบทบาทของเรา ตามตารางสายอนุมัติ
--
-- ข้อสุดท้ายยึดจาก "สายอนุมัติ" ไม่ใช่ "มีใบค้างอยู่หรือไม่" เพราะคิวต้องอ่าน
-- ชื่อได้ตั้งแต่ยังไม่มีใบ และฝ่ายบุคคลแก้สายอนุมัติเมื่อไร สิทธิ์ก็ขยับตามเอง
-- คนที่ไม่ได้เป็นผู้อนุมัติของใคร (เช่นพนักงานขาย) ยังเห็นแค่ตัวเองเหมือนเดิม
-- ─────────────────────────────────────────────────────────────────

drop policy employees_read on public.employees;

create policy employees_read on public.employees for select to authenticated
  using (
    id = public.my_employee_id()
    or public.has_role('hr')
    or boss_id = public.my_employee_id()
    or exists (
      select 1 from public.approval_routes r
       where r.from_role = public.employees.position
         and r.approver_role = any (public.my_roles())
    )
  );
