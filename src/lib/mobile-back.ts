"use client";

/*
 * ปุ่มย้อนกลับบนแถบหัวมือถือ — ปกติพากลับ "หน้าหลัก" ของบทบาท
 *
 * บางหน้ามีหน้าซ้อนอยู่ข้างใน (เช่นโปรไฟล์: หน้ารวม → เรื่องย่อย) ถ้าปุ่มบนแถบหัวพากลับหน้าหลักอย่างเดียว
 * หน้าพวกนี้ต้องมีปุ่มย้อนกลับของตัวเองอีกอัน กลายเป็นปุ่มย้อนกลับสองอันในจอเดียว (เจ้าของทักท้วง 1 ต.ค. 2569)
 * หน้าที่มีหน้าซ้อนจึงฝากทางกลับไว้ที่นี่ แถบหัวจะเรียกอันนี้ก่อน ถ้าไม่มีค่อยกลับหน้าหลักตามเดิม
 */

let handler: (() => void) | null = null;

/** ฝากทางกลับของหน้าซ้อน — ส่ง null เมื่อปิดหน้าซ้อนแล้ว */
export function setMobileBack(fn: (() => void) | null) {
  handler = fn;
}

/** เรียกทางกลับที่ฝากไว้ · คืน true ถ้ามีคนรับไปแล้ว แถบหัวจะได้ไม่พากลับหน้าหลักซ้ำ */
export function runMobileBack() {
  if (!handler) return false;
  handler();
  return true;
}
